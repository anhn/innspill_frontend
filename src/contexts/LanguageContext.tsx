// Component export for Fast Refresh compatibility
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem("eduai-language");
    return (saved === "no" ? "no" : saved === "vi" ? "vi" : saved === "en" ? "en" : "no") as Language;
  });

  useEffect(() => {
    localStorage.setItem("eduai-language", language);
  }, [language]);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
  };

  const t = (key: string): string => {
    // Safety check: ensure translations[language] exists before accessing
    if (!translations[language]) {
      console.warn(`Language "${language}" not found in translations, falling back to "en"`);
      return translations["en"]?.[key] || key;
    }
    return translations[language][key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

// Hook export - must be separate from component for Fast Refresh
export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return context;
}
